import { createWorkersAI } from "workers-ai-provider";
import { routeAgentRequest } from "agents";
import { AIChatAgent, type OnChatMessageOptions } from "@cloudflare/ai-chat";
import { dedupeAiBinding } from "./dedupe-ai-binding";
import { convertToModelMessages, pruneMessages, streamText } from "ai";

export class IncidentAgent extends AIChatAgent<Env> {
  maxPersistedMessages = 100;
  chatRecovery = true;

  async onChatMessage(_onFinish: unknown, options?: OnChatMessageOptions) {
    // Wrapped to stop Llama 3.3 tokens being emitted twice (see dedupe-ai-binding.ts)
    const workersai = createWorkersAI({
      binding: dedupeAiBinding(this.env.AI)
    });

    const result = streamText({
      model: workersai("@cf/meta/llama-3.3-70b-instruct-fp8-fast", {
        sessionAffinity: this.sessionAffinity
      }),
      system: `You are an on-call incident assistant helping an engineer debug a production incident. The engineer will paste alerts, logs and observations. Be concise and concrete: suggest likely causes, what to check next, and how to confirm or rule out each hypothesis.`,
      // Prune old tool calls and reasoning to save tokens on long conversations
      messages: pruneMessages({
        messages: await convertToModelMessages(this.messages),
        toolCalls: "before-last-2-messages",
        reasoning: "before-last-message"
      }),
      abortSignal: options?.abortSignal
    });

    return result.toUIMessageStreamResponse();
  }
}

export default {
  async fetch(request: Request, env: Env) {
    return (
      (await routeAgentRequest(request, env)) ||
      new Response("Not found", { status: 404 })
    );
  }
} satisfies ExportedHandler<Env>;
